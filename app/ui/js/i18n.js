let LANG = "uk";

function t(key, params) {
  let s = I18N[LANG]?.[key] ?? I18N.uk[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

function setLang(code, silent) {
  if (!I18N[code]) code = "uk";
  LANG = code;
  document.documentElement.lang = code;
  applyI18n();
  const sel = document.getElementById("lang-sel");
  if (sel) sel.value = code;
  if (!silent) {
    persist();
    // перемалювати динамічні частини
    if (typeof renderTree === "function") renderTree();
    if (typeof renderDetail === "function") renderDetail();
    if (typeof renderProfileList === "function") renderProfileList();
    if (typeof renderProjectList === "function") renderProjectList();
    if (typeof renderPerf === "function") renderPerf();
    if (typeof renderSnippets === "function") renderSnippets();
  }
}

/* застосувати переклад до статичної розмітки */
function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
}
